def format_citation_label(number: Union[int, str]) -> str:
    """
    Format a positive integer citation number into standard academic bracket format: [1], [2], etc.
    Accepts positive int or numeric str (e.g. 1, '1', or '[1]').
    """
    if isinstance(number, bool):
        raise InvalidCitationError(f"Citation number must be a positive integer, got boolean {number}.")
    if isinstance(number, str):
        cleaned = number.strip().lstrip("[").rstrip("]").strip()
        try:
            val = int(cleaned)
        except ValueError:
            raise InvalidCitationError(f"Invalid citation number string: '{number}'")
    elif isinstance(number, int):
        val = number
    else:
        raise InvalidCitationError(f"Citation number must be a positive integer, got {type(number)}.")

    if val <= 0:
        raise InvalidCitationError(f"Citation number must be a positive integer, got {val}.")

    return f"[{val}]"


def parse_citation_label(label: Union[str, int]) -> int:
    """
    Parse a bracketed citation label '[1]' or numeric string '1' into its positive integer value.
    """
    if not isinstance(label, (str, int)) or isinstance(label, bool):
        raise InvalidCitationError(f"Citation label must be a string or int, got {type(label)}.")
    cleaned = str(label).strip()
    if cleaned.startswith("[") and cleaned.endswith("]"):
        cleaned = cleaned[1:-1].strip()
    try:
        val = int(cleaned)
        if val <= 0:
            raise ValueError()
        return val
    except ValueError:
        raise InvalidCitationError(f"Cannot parse valid positive integer from citation label '{label}'.")


def extract_sources_from_payload(payload: Any) -> List[Dict[str, Any]]:
    """
    Recursively/iteratively extract source references from AI endpoint responses or data dicts.
    Supports single-paper answers, multi-paper comparison, gap analysis, thematic analysis,
    and research trends.
    """
    sources: List[Dict[str, Any]] = []
    if payload is None:
        return sources

    if isinstance(payload, list):
        for item in payload:
            sources.extend(extract_sources_from_payload(item))
        return sources

    if isinstance(payload, dict):
        # 1. If payload contains top-level sources list
        if "sources" in payload and isinstance(payload["sources"], list):
            for s in payload["sources"]:
                if isinstance(s, dict):
                    sources.append(s)

        # 2. If payload contains top-level source_refs list
        if "source_refs" in payload and isinstance(payload["source_refs"], list):
            for s in payload["source_refs"]:
                if isinstance(s, dict):
                    sources.append(s)

        # 3. Known multi-paper sections
        section_keys = [
            "comparison", "gap_analysis", "thematic_analysis", "trend_analysis",
            "similarities", "differences", "methodology_comparison", "findings_comparison",
            "research_gaps", "common_limitations", "methodological_gaps", "dataset_population_gaps",
            "understudied_areas", "contradictions_inconsistencies", "unanswered_research_questions",
            "future_research_directions", "themes", "research_evolution", "emerging_directions",
            "methodology_evolution", "future_directions", "papers"
        ]
        for key in section_keys:
            if key in payload and payload[key] is not None:
                sources.extend(extract_sources_from_payload(payload[key]))

        # 4. If payload itself is a single source dict (has paper_id or citation_id, but not a container)
        if ("paper_id" in payload or "citation_id" in payload or "chunk_id" in payload):
            if "overall_synthesis" not in payload and "comparison" not in payload and "themes" not in payload and "trend_analysis" not in payload and "gap_analysis" not in payload:
                sources.append(payload)

    return sources


def build_citation_map(
    items: Union[List[Any], QuerySet, ResearchMessage, Dict[str, Any]],
    start_number: int = 1,
    expected_project: Optional[Any] = None,
    allowed_papers: Optional[Union[List[Paper], Dict[int, Paper]]] = None,
    valid_chunk_map: Optional[Dict[int, PaperChunk]] = None,
) -> Dict[str, Dict[str, Any]]:
    """
    Build a deterministic, structured citation map for frontend and API responses.
    Number citations deterministically based on their first appearance:
        cite_p1_c4 -> [1]
        cite_p2_c7 -> [2]
        cite_p1_c9 -> [3]
    Duplicate citation IDs receive only one citation number.
    Missing page numbers are preserved as None without inventing page numbers.
    Structure:
    {
      "1": {
        "citation_id": "cite_p1_c4",
        "paper_id": 1,
        "paper_title": "...",
        "chunk_id": 4,
        "page_number": 3,
        "evidence_id": 17
      }
    }
    """
    if not isinstance(start_number, int) or isinstance(start_number, bool) or start_number < 1:
        raise InvalidCitationError("start_number must be a positive integer >= 1.")

    expected_project_id = None
    if expected_project is not None:
        expected_project_id = expected_project.id if hasattr(expected_project, "id") else int(expected_project)

    paper_map = None
    if allowed_papers is not None:
        paper_map = allowed_papers if isinstance(allowed_papers, dict) else {p.id: p for p in allowed_papers}

    # Resolve items container
    raw_list: List[Any] = []
    if isinstance(items, ResearchMessage):
        raw_list = list(items.evidence.select_related("paper", "chunk").order_by("created_at"))
    elif hasattr(items, "select_related"):  # QuerySet
        raw_list = list(items)
    elif isinstance(items, dict):
        raw_list = extract_sources_from_payload(items)
    elif isinstance(items, list):
        raw_list = items
    elif items is None:
        raw_list = []
    else:
        raise InvalidCitationError(f"Unsupported items type for build_citation_map: {type(items)}")

    citation_map: Dict[str, Dict[str, Any]] = {}
    seen_citation_ids: Dict[str, int] = {}
    current_number = start_number

    for item in raw_list:
        if item is None:
            continue

        cid: Optional[str] = None
        pid: Optional[int] = None
        cid_chunk: Optional[int] = None
        ptitle: str = ""
        pnum: Optional[int] = None
        ev_id: Optional[int] = None

        if isinstance(item, ResearchEvidence):
            if expected_project_id is not None and item.paper.project_id != expected_project_id:
                raise CrossProjectCitationError(
                    f"Cross-project evidence rejected: evidence {item.id} belongs to project "
                    f"{item.paper.project_id}, expected {expected_project_id}."
                )
            if paper_map is not None and item.paper_id not in paper_map:
                raise InvalidCitationError(f"Paper ID {item.paper_id} is not in allowed papers.")

            cid = item.citation_id
            pid = item.paper_id
            cid_chunk = item.chunk_id
            ptitle = item.paper.title
            pnum = item.page_number
            ev_id = item.id

        elif isinstance(item, CitationReference):
            if expected_project_id is not None:
                db_paper = Paper.objects.filter(id=item.paper_id).first()
                if db_paper and db_paper.project_id != expected_project_id:
                    raise CrossProjectCitationError(
                        f"Cross-project reference rejected: paper {item.paper_id} belongs to "
                        f"project {db_paper.project_id}, expected {expected_project_id}."
                    )
            if paper_map is not None and item.paper_id not in paper_map:
                raise InvalidCitationError(f"Paper ID {item.paper_id} is not in allowed papers.")

            cid = item.citation_id
            pid = item.paper_id
            cid_chunk = item.chunk_id
            ptitle = item.paper_title
            pnum = item.page_number
            ev_id = item.evidence_id

        elif isinstance(item, NumberedCitation):
            cid = item.citation_id
            pid = item.paper_id
            cid_chunk = item.chunk_id
            ptitle = item.paper_title
            pnum = item.page_number
            ev_id = item.evidence_id

        elif isinstance(item, dict):
            validated = validate_source_dict(
                source=item,
                valid_chunk_map=valid_chunk_map,
                allowed_papers=paper_map,
                expected_project=expected_project_id,
            )
            cid = validated["citation_id"]
            pid = validated["paper_id"]
            cid_chunk = validated["chunk_id"]
            ptitle = validated["paper_title"]
            pnum = validated["page_number"]
            raw_ev_id = item.get("evidence_id")
            if raw_ev_id is not None:
                try:
                    ev_id = int(raw_ev_id)
                except (ValueError, TypeError):
                    raise InvalidCitationError(f"Invalid evidence_id in source dict: {raw_ev_id}")

        elif isinstance(item, str):
            parsed = parse_citation_id(item)
            pid = parsed["paper_id"]
            cid_chunk = parsed["chunk_id"]
            cid = item
            if expected_project_id is not None or paper_map is not None:
                db_paper = Paper.objects.filter(id=pid).first()
                if not db_paper:
                    raise InvalidCitationError(f"Paper ID {pid} does not exist.")
                if expected_project_id is not None and db_paper.project_id != expected_project_id:
                    raise CrossProjectCitationError(
                        f"Cross-project citation rejected: paper {pid} belongs to project {db_paper.project_id}."
                    )
                if paper_map is not None and pid not in paper_map:
                    raise InvalidCitationError(f"Paper ID {pid} is not in allowed papers.")
                ptitle = db_paper.title
            else:
                db_paper = Paper.objects.filter(id=pid).first()
                ptitle = db_paper.title if db_paper else ""

        else:
            raise InvalidCitationError(f"Unsupported citation item type: {type(item)}")

        # Deduplication check by citation_id
        if cid in seen_citation_ids:
            existing_num = seen_citation_ids[cid]
            existing_key = str(existing_num)
            if ev_id is not None and citation_map[existing_key].get("evidence_id") is None:
                citation_map[existing_key]["evidence_id"] = ev_id
            continue

        assigned_num = current_number
        seen_citation_ids[cid] = assigned_num
        citation_map[str(assigned_num)] = {
            "citation_id": cid,
            "paper_id": pid,
            "paper_title": ptitle,
            "chunk_id": cid_chunk,
            "page_number": pnum,
            "evidence_id": ev_id,
        }
        current_number += 1

    return citation_map


def resolve_citation_by_number(
    citation_map: Dict[str, Dict[str, Any]],
    number: Union[int, str],
) -> Dict[str, Any]:
    """
    Resolve a citation number ([1], '1', 1) back to its citation metadata entry from citation_map.
    Raises CitationResolutionError if the citation number is not found.
    """
    if not isinstance(citation_map, dict):
        raise InvalidCitationError(f"citation_map must be a dictionary, got {type(citation_map)}.")

    num_int = parse_citation_label(number)
    key = str(num_int)
    if key not in citation_map:
        raise CitationResolutionError(f"Citation [{key}] could not be resolved in the provided citation map.")

    return citation_map[key]


def get_citation_number_for_id(
    citation_map: Dict[str, Dict[str, Any]],
    citation_id: str,
) -> Optional[int]:
    """
    Find the assigned sequential citation number for a given citation_id in citation_map.
    Returns integer number (e.g. 1) or None if not present.
    """
    if not isinstance(citation_map, dict) or not isinstance(citation_id, str):
        return None

    for key, val in citation_map.items():
        if isinstance(val, dict) and val.get("citation_id") == citation_id:
            try:
                return int(key)
            except ValueError:
                pass
    return None


def get_citation_label_for_id(
    citation_map: Dict[str, Dict[str, Any]],
    citation_id: str,
) -> Optional[str]:
    """
    Find the bracketed citation label '[N]' for a given citation_id in citation_map.
    """
    num = get_citation_number_for_id(citation_map, citation_id)
    if num is not None:
        return format_citation_label(num)
    return None


def format_citations_summary(
    citation_map: Dict[str, Dict[str, Any]],
) -> List[Dict[str, Any]]:
    """
    Return a list of numbered citations ordered sequentially:
    [
        {"number": 1, "label": "[1]", **citation_entry},
        {"number": 2, "label": "[2]", **citation_entry},
    ]
    """
    if not isinstance(citation_map, dict):
        raise InvalidCitationError(f"citation_map must be a dictionary, got {type(citation_map)}.")

    summary = []
    sorted_keys = sorted([k for k in citation_map.keys() if k.isdigit()], key=int)
    for k in sorted_keys:
        entry = citation_map[k]
        num = int(k)
        summary.append({
            "number": num,
            "label": format_citation_label(num),
            **entry,
        })
    return summary

